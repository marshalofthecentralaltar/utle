/**
 * Writes extension/README.md "What to say" from src/core/phrases.ts (docs/ARCHITECTURE.md 30.2.6),
 * between the two marker comments, so the README cannot drift from the help page and the tests.
 *
 *   npx tsx scripts/phrases-doc.ts           writes the section
 *   npx tsx scripts/phrases-doc.ts --check   exits 1 when the section is not what the source gives
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PHRASE_GROUPS, phraseFormCount } from '../src/core/phrases.ts'

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const README = join(repoRoot, 'extension', 'README.md')
export const START = '<!-- phrases:start: generated by `npx tsx scripts/phrases-doc.ts` from src/core/phrases.ts; edit the source, not this -->'
export const END = '<!-- phrases:end -->'

const cell = (text: string): string => text.replace(/\|/g, '\\|')

/** The section between the markers, markers excluded. */
export function phrasesSection(): string {
  const entries = PHRASE_GROUPS.reduce((n, g) => n + g.phrases.length, 0)
  const out: string[] = [
    '',
    `Generated from \`src/core/phrases.ts\`, the one source of the phrases: the help page (\`extension/help.html\`, say \`abi\`) shows it, the new-tab page rotates its examples, and \`src/core/phrases.test.ts\` runs every Estonian form below through the rule it names (\`src/core/inpage.ts\`, \`src/core/browserIntent.ts\`, \`src/core/places.ts\`, \`src/core/savedEntry.ts\`, \`src/core/reading.ts\`, \`src/core/wake.ts\`), so a phrase that drifts fails \`npm run check\`. ${phraseFormCount()} Estonian forms in ${entries} entries and ${PHRASE_GROUPS.length} groups. The full tables are \`docs/ARCHITECTURE.md\` 21.1, 22, 23.4 and 30.2. Anything that is not a command is typed into the message box; what no fixed phrase covers goes to the model with what is on the page.`,
  ]
  for (const group of PHRASE_GROUPS) {
    out.push('', `### ${group.name} (${group.nameEn})`, '', `Help page: \`help.html#${group.id}\`, or say \`abi ${group.say[0] ?? group.id}\`.`, '', '| Estonian | English | What happens |', '|---|---|---|')
    for (const p of group.phrases) out.push(`| ${p.et.map((f) => `\`${cell(f)}\``).join(', ')} | ${cell(p.en)} | ${cell(p.doesEn)} |`)
    out.push('', group.noteEn)
  }
  out.push('')
  return out.join('\n')
}

/** The README with the section replaced. Throws when a marker is missing. */
export function withSection(readme: string): string {
  const eol = readme.includes('\r\n') ? '\r\n' : '\n'
  const text = readme.replace(/\r\n/g, '\n')
  const start = text.indexOf(START)
  const end = text.indexOf(END)
  if (start < 0 || end < start) throw new Error(`extension/README.md needs the two markers:\n${START}\n${END}`)
  const next = `${text.slice(0, start + START.length)}\n${phrasesSection()}\n${text.slice(end)}`
  return next.replace(/\n/g, eol)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const before = readFileSync(README, 'utf8')
  const after = withSection(before)
  if (process.argv.includes('--check')) {
    if (after !== before) {
      console.error('extension/README.md "What to say" is not what src/core/phrases.ts gives: run npx tsx scripts/phrases-doc.ts')
      process.exitCode = 1
    } else console.log('extension/README.md "What to say" matches src/core/phrases.ts')
  } else {
    writeFileSync(README, after)
    console.log(`extension/README.md "What to say": ${phraseFormCount()} Estonian forms in ${PHRASE_GROUPS.length} groups`)
  }
}
